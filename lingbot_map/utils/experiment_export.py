"""Export LingBot-Map predictions for reproducible downstream experiments."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np


def _to_numpy(value: Any) -> np.ndarray | None:
    if isinstance(value, np.ndarray):
        return value
    if hasattr(value, "detach") and hasattr(value, "cpu") and hasattr(value, "numpy"):
        value = value.detach().cpu()
        if str(getattr(value, "dtype", "")) == "torch.bfloat16":
            value = value.float()
        return value.numpy()
    return None


def _write_binary_ply(
    output_path: Path,
    points: np.ndarray,
    colors: np.ndarray,
    confidence: np.ndarray,
) -> None:
    vertex_dtype = np.dtype(
        [
            ("x", "<f4"),
            ("y", "<f4"),
            ("z", "<f4"),
            ("red", "u1"),
            ("green", "u1"),
            ("blue", "u1"),
            ("confidence", "<f4"),
        ]
    )
    vertices = np.empty(points.shape[0], dtype=vertex_dtype)
    vertices["x"], vertices["y"], vertices["z"] = points.T
    vertices["red"], vertices["green"], vertices["blue"] = colors.T
    vertices["confidence"] = confidence

    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        "comment Generated by LingBot-Map experiment export\n"
        f"element vertex {len(vertices)}\n"
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "property uchar red\n"
        "property uchar green\n"
        "property uchar blue\n"
        "property float confidence\n"
        "end_header\n"
    )
    with output_path.open("wb") as f:
        f.write(header.encode("ascii"))
        vertices.tofile(f)


def _save_point_cloud(
    output_path: Path,
    predictions: dict[str, Any],
    images: np.ndarray,
    confidence_threshold: float,
    stride: int,
) -> int:
    points = _to_numpy(predictions.get("world_points"))
    confidence = _to_numpy(
        predictions.get("world_points_conf", predictions.get("depth_conf"))
    )
    if points is None or confidence is None:
        return 0

    stride = max(1, int(stride))
    points = points[:, ::stride, ::stride]
    confidence = confidence[:, ::stride, ::stride]
    colors = images[:, ::stride, ::stride]

    points = points.reshape(-1, 3).astype(np.float32, copy=False)
    confidence = confidence.reshape(-1).astype(np.float32, copy=False)
    colors = colors.reshape(-1, 3)
    if np.issubdtype(colors.dtype, np.floating):
        colors = (colors * 255.0).clip(0, 255).astype(np.uint8)
    else:
        colors = colors.clip(0, 255).astype(np.uint8, copy=False)

    valid = np.isfinite(points).all(axis=1)
    valid &= np.isfinite(confidence)
    valid &= confidence >= float(confidence_threshold)
    points, colors, confidence = points[valid], colors[valid], confidence[valid]

    _write_binary_ply(output_path, points, colors, confidence)
    return int(points.shape[0])


def _save_trajectory(output_path: Path, extrinsic: np.ndarray) -> None:
    with output_path.open("w", encoding="utf-8") as f:
        f.write("# frame_idx and row-major 3x4 camera-to-world matrix\n")
        for i, pose in enumerate(extrinsic):
            values = " ".join(f"{float(v):.10f}" for v in pose.reshape(-1))
            f.write(f"{i} {values}\n")


def _save_trajectory_plot(output_path: Path, extrinsic: np.ndarray) -> bool:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False

    centers = extrinsic[:, :3, 3]
    fig, ax = plt.subplots(figsize=(7, 7))
    ax.plot(centers[:, 0], centers[:, 2], "-o", linewidth=1.2, markersize=2)
    ax.scatter(centers[0, 0], centers[0, 2], c="green", label="start", zorder=3)
    ax.scatter(centers[-1, 0], centers[-1, 2], c="red", label="end", zorder=3)
    ax.set_xlabel("X")
    ax.set_ylabel("Z")
    ax.set_title("Camera trajectory (top view)")
    ax.axis("equal")
    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)
    return True


def export_experiment_outputs(
    output_dir: str | Path,
    predictions: dict[str, Any],
    images: Any,
    source_paths: list[str],
    run_config: dict[str, Any],
    confidence_threshold: float = 1.5,
    point_stride: int = 4,
) -> dict[str, Any]:
    """Export raw predictions, a colored point cloud, trajectory, and metadata."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    arrays = {}
    for key, value in predictions.items():
        array = _to_numpy(value)
        if array is not None:
            arrays[key] = array

    images_array = _to_numpy(images)
    if images_array is None:
        raise ValueError("images must be a NumPy array or CPU tensor")
    if images_array.ndim == 5 and images_array.shape[0] == 1:
        images_array = images_array[0]
    if images_array.ndim == 4 and images_array.shape[1] == 3:
        images_hwc = images_array.transpose(0, 2, 3, 1)
    elif images_array.ndim == 4 and images_array.shape[-1] == 3:
        images_hwc = images_array
    else:
        raise ValueError(f"Expected images with shape [S,3,H,W] or [S,H,W,3], got {images_array.shape}")

    predictions_path = output_dir / "predictions.npz"
    np.savez(predictions_path, **arrays)

    if np.issubdtype(images_hwc.dtype, np.floating):
        images_uint8 = (images_hwc * 255.0).clip(0, 255).astype(np.uint8)
    else:
        images_uint8 = images_hwc.clip(0, 255).astype(np.uint8, copy=False)
    np.save(output_dir / "images.npy", images_uint8)

    point_count = _save_point_cloud(
        output_dir / "point_cloud.ply",
        arrays,
        images_hwc,
        confidence_threshold=confidence_threshold,
        stride=point_stride,
    )

    trajectory_saved = False
    trajectory_plot_saved = False
    extrinsic = arrays.get("extrinsic")
    if extrinsic is not None:
        _save_trajectory(output_dir / "trajectory.txt", extrinsic)
        trajectory_saved = True
        trajectory_plot_saved = _save_trajectory_plot(
            output_dir / "trajectory.png", extrinsic
        )

    metadata = {
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "source_paths": [str(p) for p in source_paths],
        "run_config": run_config,
        "arrays": {
            key: {"shape": list(value.shape), "dtype": str(value.dtype)}
            for key, value in arrays.items()
        },
        "images": {"shape": list(images_uint8.shape), "dtype": str(images_uint8.dtype)},
        "exports": {
            "predictions": str(predictions_path.name),
            "images": "images.npy",
            "point_cloud": "point_cloud.ply" if point_count else None,
            "point_count": point_count,
            "point_stride": max(1, int(point_stride)),
            "confidence_threshold": float(confidence_threshold),
            "trajectory": "trajectory.txt" if trajectory_saved else None,
            "trajectory_plot": "trajectory.png" if trajectory_plot_saved else None,
        },
    }
    with (output_dir / "run_info.json").open("w", encoding="utf-8") as f:
        json.dump(metadata, f, ensure_ascii=False, indent=2)

    return metadata
